import { createClient } from "@supabase/supabase-js";

type AppointmentInsert = {
  id?: string;
  reference: string;
  service_id: string;
  stylist_id: string;
  location_id: string;
  date: string;
  time: string;
  guest_name: string;
  guest_email: string;
  guest_phone: string;
  guest_notes?: string;
  amount: number;
  status?: string;
  created_at?: string;
};

type MessageInsert = {
  id?: string;
  name: string;
  email: string;
  phone?: string;
  studio?: string;
  subject: string;
  message: string;
  created_at?: string;
  approved?: boolean;
  approved_at?: string | null;
};

/** Hand-written schema (not generated by the Supabase CLI) covering just the two tables this app uses. */
export type Database = {
  public: {
    Tables: {
      appointments: {
        Row: Required<AppointmentInsert>;
        Insert: AppointmentInsert;
        Update: Partial<AppointmentInsert>;
        Relationships: [];
      };
      messages: {
        Row: Required<MessageInsert>;
        Insert: MessageInsert;
        Update: Partial<MessageInsert>;
        Relationships: [];
      };
    };
    Views: Record<string, never>;
    Functions: Record<string, never>;
    Enums: Record<string, never>;
    CompositeTypes: Record<string, never>;
  };
};

const supabaseUrl = process.env.SUPABASE_URL;
const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseUrl || !serviceRoleKey) {
  throw new Error("SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY is not set.");
}

declare global {
  var __orielleSupabase: ReturnType<typeof createClient<Database>> | undefined;
}

/** Server-only client using the service_role key — bypasses RLS, never import this from a client component. */
export const supabase =
  globalThis.__orielleSupabase ??
  createClient<Database>(supabaseUrl, serviceRoleKey, {
    auth: { persistSession: false },
  });

if (process.env.NODE_ENV !== "production") globalThis.__orielleSupabase = supabase;
